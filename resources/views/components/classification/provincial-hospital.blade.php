      <div class="modal-body">
        <p class="p-modal text-justify" data-modal-section="overview">
            General Hospitals, usually called provincial hospitals, are the secondary-care tier. Under the RDP, a General Hospital is established &ldquo;where there is a population greater than 20,000 or the facility is the only general hospital facility for a Province.&rdquo; WHO&rsquo;s 2014 profile counted nine provincial hospitals: seven small hospitals serving populations of 20,000&ndash;60,000, and two large hospitals serving 60,000&ndash;100,000 or more. Three of these are run by church or non-government organizations (see the Private Hospitals and Clinics section). Health is a provincial service under Schedule 5 of the Provincial Government Act 1997, and provincial health departments manage these hospitals with MHMS funding and oversight.
        </p>
        <p class="p-modal text-justify">
            <strong>Note:</strong> The Health Services Act uses the single term &ldquo;hospital&rdquo; for both the NRH and the provincial hospitals and does not separate them into grades (Section 2). The distinction between National Referral Hospital and General Hospital exists only in the RDP. The 2014 small/large split is descriptive and comes from a WHO source. For a formal classification, use &ldquo;General Hospital (provincial)&rdquo; regardless of size.
        </p>
        <ul data-modal-section="role">
            <li>Serve as the main referral hospital for the province, receiving cases from Area Health Centers and Rural Health Centers</li>
            <li>Provide primary and secondary care, both outpatient and inpatient; refer cases beyond provincial capability to the NRH</li>
            <li>Supervise primary care in the province: at provincial-hospital level the Assistant Director of Nursing oversees and supervises the province&rsquo;s AHCs, RHCs and nurse aid posts.</li>
        </ul>
        <h6 class="fw-bold" data-modal-section="services">Core Capability Areas</h6>
        <ul>
            <li>Under the RDP: all general medical services, general surgery and operating theatre, accident and emergency, x-ray and ultrasound, physiotherapy, dietetics and clinical outreach</li>
            <li>Pediatric, surgical and maternity services, staffed by doctors who have completed a broad two-year internship (WHO, 2014)</li>
        </ul>
        <h6 class="fw-bold">Typical Bed Capacity</h6>
        <ul>
            <li>Not set by the RDP; staffing is based on ward caseload, with at least one midwife on each shift</li>
        </ul>
        <p class="p-modal text-justify">
            <em><strong>Note:</strong> Legal basis: Health Services Act (Cap. 100), Sections 2 and 7&ndash;9; Provincial Government Act 1997, Schedule 5. Facility counts and size bands come from WHO (2014) and are dated; the RDP service package is policy, not statute.</em>
